#!/bin/bash

# ============================================================
# 冲压车间垫板货架层位绑定管理系统 - 停止脚本
# ============================================================

set -e

# 颜色定义
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
BLUE='\033[0;34m'
NC='\033[0m'

echo ""
echo -e "${BLUE}============================================================${NC}"
echo -e "${BLUE}  冲压车间垫板货架层位绑定管理系统 - 停止脚本${NC}"
echo -e "${BLUE}============================================================${NC}"
echo ""

echo -e "${YELLOW}[INFO]${NC} 正在停止所有服务..."
docker compose down

echo -e "${GREEN}[OK]${NC} 所有服务已停止"
echo ""

echo -e "${BLUE}[INFO]${NC} 如需清除数据卷，请执行: ${YELLOW}docker compose down -v${NC}"
echo -e "${BLUE}[INFO]${NC} 如需重新启动，请执行: ${YELLOW}./start.sh${NC}"
echo ""
